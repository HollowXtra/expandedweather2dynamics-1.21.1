    private void renderSidebar(GuiGraphics g, int mx, int my) {
        sidebarScroll = clamp(sidebarScroll, 0, maxSidebarScroll());
        if (categoryGrow == null || categoryGrow.length != categories.size()) {
            categoryGrow = new float[categories.size()];
        }
        List<SideLine> lines = sideLines();
        g.enableScissor(sidebarX, sidebarY, sidebarX + sidebarW, sidebarY + sidebarH);
        for (SideLine line : lines) {
            if (line.y() + line.h() < sidebarY || line.y() > sidebarY + sidebarH) {
                continue;
            }
            Category c = categories.get(line.category());
            if (line.sub() >= 0) {
                // A sub-entry: a bullet, the nested section's name, and a hover tint. Clicking it scrolls the
                // body to that stretch of settings.
                if (line.sub() >= c.subs.size()) {
                    continue;
                }
                boolean hover = mx >= sidebarX && mx <= sidebarX + sidebarW && my >= line.y() && my <= line.y() + line.h();
                RoundedRectRenderer.render(g, sidebarX + 26, line.y() + 3, 2, 2, 1, hover ? ACCENT_LIGHT : TEXT_FAINT);
                g.drawString(font, font.plainSubstrByWidth(c.subs.get(line.sub()).name(), sidebarW - 46),
                        sidebarX + 34, line.y() + 3, hover ? TEXT : TEXT_DIM);
                continue;
            }
            int y = line.y();
            boolean sel = line.category() == selected;
            boolean hover = mx >= sidebarX && mx <= sidebarX + sidebarW && my >= y && my <= y + SIDE_ITEM_H;
            float target = hover ? 1.0F : 0.0F;
            categoryGrow[line.category()] += (target - categoryGrow[line.category()]) * 0.22F;
            if (Math.abs(categoryGrow[line.category()] - target) < 0.01F) {
                categoryGrow[line.category()] = target;
            }
            float grow = categoryGrow[line.category()] * 1.5F;
            float px = sidebarX + 1 - grow;
            float py = y + 1 - grow * 0.5F;
            float pw = sidebarW - 2 + grow * 2.0F;
            float ph = SIDE_ITEM_H - 3 + grow;
            if (sel) {
                RoundedRectRenderer.box(g, px, py, pw, ph, 6, 0xFF17202B, ACCENT);
                g.fill(sidebarX + 4, y + 6, sidebarX + 6, y + SIDE_ITEM_H - 8, ACCENT_LIGHT);
            } else if (grow > 0.01F) {
                RoundedRectRenderer.render(g, px, py, pw, ph, 6,
                        (((int) (grow * 40.0F)) << 24) | (PILL_HOVER & 0xFFFFFF));
            } else {
                RoundedRectRenderer.render(g, px, py, pw, ph, 6, 0x00000000);
            }
            int iconX = sidebarX + 12;
            if (!c.icon.isEmpty()) {
                g.renderItem(c.icon, iconX, y + (SIDE_ITEM_H - 16) / 2);
            } else {
                g.drawString(font, c.glyph, iconX + 3, y + (SIDE_ITEM_H - 9) / 2, sel ? ACCENT_LIGHT : TEXT_DIM);
            }
            int labelColor = sel ? 0xFFEAF2FB : (hover ? TEXT : TEXT_DIM);
            g.drawString(font, c.name.toUpperCase(Locale.ROOT), sidebarX + 34, y + (SIDE_ITEM_H - 9) / 2, labelColor);
            RoundedRectRenderer.chevron(g, sidebarX + sidebarW - 14, y + SIDE_ITEM_H / 2, line.category() != expanded,
                    sel ? ACCENT_LIGHT : TEXT_FAINT);
        }
        g.disableScissor();
    }

    private void renderBody(GuiGraphics g, int mx, int my, float pt) {
        if (!query().equals(lastQuery)) {
            lastQuery = query();
            rebuildHits();
            bodyScroll = 0;
            highlightRow = null;
        }
        boolean searchMode = searching();
        List<ConfigRow> rows = visibleRows();
        int rowsH = bodyH - 26;
        double total = rows.size() * (double) ConfigRow.HEIGHT;
        maxBodyScroll = Math.max(0, total - rowsH);
        bodyScroll = clamp(bodyScroll, 0, maxBodyScroll);
        thumbH = Math.max(24, rowsH * Math.min(1, rowsH / Math.max(total, 1)));
        double thumbY = bodyY + 26 + (rowsH - thumbH) * (maxBodyScroll == 0 ? 0 : bodyScroll / maxBodyScroll);
        int trackX = bodyX + bodyW - 6;
        g.fill(trackX, bodyY + 26, trackX + 3, bodyY + bodyH, 0xFF161B21);
        RoundedRectRenderer.render(g, trackX, (float) thumbY, 3, (float) thumbH, 1.5f, 0xFF5C6672);

        // Section bar: the category's own name, with the illustration column's header drawn to match it.
        String header = searchMode
                ? spaceOut(hits.isEmpty() ? "NO MATCHES" : "SEARCH RESULTS")
                : spaceOut(categories.get(selected).name.toUpperCase(Locale.ROOT));
        RoundedRectRenderer.render(g, bodyX, bodyY, rowsW, 20, 4, 0xFF161B21);
        g.drawString(font, header, bodyX + 8, bodyY + 6, searchMode ? GOLD : TEXT);
        if (illusW > 0 && !searchMode) {
            renderIllustration(g, bodyY, bodyH);
        }

        g.enableScissor(bodyX, bodyY, bodyX + rowsW, bodyY + bodyH);
        for (int i = 0; i < rows.size(); i++) {
            int y = rowsTop + i * ConfigRow.HEIGHT - (int) bodyScroll;
            if (y + ConfigRow.HEIGHT < bodyY || y > bodyY + bodyH) {
                continue;
            }
            ConfigRow row = rows.get(i);
            boolean hover = mx >= bodyX && mx <= bodyX + rowsW && my >= y && my <= y + ConfigRow.HEIGHT;
            if (hover) {
                g.fill(bodyX, y, bodyX + rowsW, y + ConfigRow.HEIGHT, searchMode ? 0x1F6FA9E8 : 0x0F6FA9E8);
            }
            g.fill(bodyX + 4, y + ConfigRow.HEIGHT - 1, bodyX + rowsW - 4, y + ConfigRow.HEIGHT, 0xFF171C23);
            if (searchMode) {
                renderHit(g, hits.get(i).category(), row, bodyX + 2, y, rowsW - 10, hover);
                continue;
            }
            boolean flash = row == highlightRow && Util.getMillis() < highlightUntil;
            if (flash) {
                drawHighlight(g, bodyX, y, rowsW);
            }
            row.render(g, font, bodyX + 4, y, rowsW - 12, mx, my, pt);
            if (flash) {
                drawHighlightOutline(g, bodyX, y, rowsW);
            }
        }
        g.disableScissor();
    }

