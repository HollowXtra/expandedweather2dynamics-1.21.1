    /**
     * The name a category is listed under. Almost every one of them is its key title-cased; the exception is
     * the simple section, whose name says what it is rather than what it is called.
     */
    private static String categoryName(String key) {
        return SIMPLE_KEY.equals(key) ? SIMPLE_NAME : ConfigRow.pretty(key);
    }

    private void buildCategories() {
        List<ConfigRow> general = new ArrayList<>();
        List<Sub> generalSubs = new ArrayList<>();
        UnmodifiableConfig root = Config.SPEC.getValues();
        for (UnmodifiableConfig.Entry e : root.entrySet()) {
            Object v = e.getValue();
            if (v instanceof ConfigValue<?> cv) {
                general.add(ConfigRow.create(cv));
            } else if (v instanceof UnmodifiableConfig section) {
                List<ConfigRow> rows = new ArrayList<>();
                List<Sub> subs = new ArrayList<>();
                walk(section, rows, subs);
                categories.add(new Category(categoryName(e.getKey()), glyph(e.getKey()), rows, subs, iconFor(e.getKey())));
            }
        }
        categories.sort(java.util.Comparator.comparing(c -> c.name));
        // The simple settings are the reason most players open this screen at all, so they are pinned above the
        // alphabetical run rather than left to land inside it. The sort above is stable, so every other
        // category keeps the A-to-Z order it was just put in.
        Category pinned = null;
        for (Category category : categories) {
            if (SIMPLE_NAME.equals(category.name)) {
                pinned = category;
                break;
            }
        }
        if (pinned != null) {
            Category first = pinned;
            categories.sort(java.util.Comparator.comparingInt(c -> c == first ? 0 : 1));
        }
        if (!general.isEmpty()) {
            categories.add(new Category("General", "\u2699", general, generalSubs, iconFor("general")));
        }
        if (categories.isEmpty()) {
            categories.add(new Category("General", "\u2699", new ArrayList<>(), generalSubs, iconFor("general")));
        }
    }

    /**
     * Flattens a section into rows, recording each nested section as a {@link Sub} at the row index it starts
     * at. The nested names are what the expanded pill lists, so the sidebar can show the shape of a category
     * without a second pass over the spec.
     */
    private static void walk(UnmodifiableConfig section, List<ConfigRow> rows, List<Sub> subs) {
        for (UnmodifiableConfig.Entry e : section.entrySet()) {
            Object v = e.getValue();
            if (v instanceof ConfigValue<?> cv) {
                rows.add(ConfigRow.create(cv));
            } else if (v instanceof UnmodifiableConfig nested) {
                subs.add(new Sub(ConfigRow.pretty(e.getKey()), rows.size()));
                walk(nested, rows, subs);
            }
        }
    }

    /**
     * The icon a category is drawn with: a real item from this mod where one exists for the subject, since a
     * settings list about weather instruments reads better with the instruments on it than with abstract
     * glyphs. Vanilla covers the rest (lightning, LOD viewing, the general fallback).
     */
    private static ItemStack iconFor(String section) {
        String s = section.toLowerCase(Locale.ROOT);
        if (SIMPLE_KEY.equals(s)) {
            // The short version is about the weather as a whole, and the anemometer is the instrument the mod's
            // storm sections already use for exactly that.
            return stack(ModContent.ANEMOMETER_BLOCK_ITEM);
        }
        if (s.contains("siren")) {
            return stack(ModContent.WEATHER_ALERT_SIREN_BLOCK_ITEM);
        }
        if (s.contains("lightning") || s.contains("thunder")) {
            return new ItemStack(Items.LIGHTNING_ROD);
        }
        if (s.contains("spc") || s.contains("risk") || s.contains("outlook")) {
            return stack(ModContent.SPC_RISK_BLOCK_ITEM);
        }
        if (s.contains("radar")) {
            return stack(ModContent.PORTABLE_RADAR_ITEM);
        }
        if (s.contains("lod") || s.contains("compat")) {
            return new ItemStack(Items.SPYGLASS);
        }
        if (s.contains("drone") || s.contains("probe")) {
            return stack(ModContent.WEATHER_DRONE_ITEM);
        }
        if (s.contains("balloon") || s.contains("sonde")) {
            return stack(ModContent.WEATHER_BALLOON_ITEM);
        }
        if (s.contains("tornado") || s.contains("vortex") || s.contains("storm") || s.contains("physics")
                || s.contains("motion") || s.contains("wind")) {
            return stack(ModContent.ANEMOMETER_BLOCK_ITEM);
        }
        if (s.contains("low_pressure") || s.contains("pressure") || s.contains("front")) {
            return stack(ModContent.BAROMETER_BLOCK_ITEM);
        }
        if (s.contains("rain") || s.contains("precip") || s.contains("downfall") || s.contains("hail")) {
            return stack(ModContent.RAIN_GAUGE_BLOCK_ITEM);
        }
        if (s.contains("ocean") || s.contains("wave") || s.contains("water") || s.contains("sea")) {
            return stack(ModContent.RAIN_GAUGE_BLOCK_ITEM);
        }
        if (s.contains("hud") || s.contains("screen") || s.contains("ui") || s.contains("display")) {
            return stack(ModContent.WEATHER_COMPUTER_BLOCK_ITEM);
        }
        if (s.contains("radio") || s.contains("alert") || s.contains("network")) {
            // The alert siren's own model, not the radio's: the radio item is one of the five whose block model
            // currently fails to bake, and an icon is exactly where that shows.
            return stack(ModContent.WEATHER_ALERT_SIREN_BLOCK_ITEM);
        }
        if (s.contains("survey") || s.contains("damage")) {
            return stack(ModContent.DAMAGE_SURVEYOR_ITEM);
        }
        return new ItemStack(Items.COMPARATOR);
    }

    private static ItemStack stack(net.neoforged.neoforge.registries.DeferredHolder<net.minecraft.world.item.Item, ?> holder) {
        try {
            return new ItemStack(holder.get());
        } catch (RuntimeException ignored) {
            // A registry that is not ready (or an entry that failed to register) falls back to the glyph.
            return ItemStack.EMPTY;
        }
    }

