    /**
     * Draws the schematic for a category. Each one is a handful of primitives chosen to say what the category is
     * about at a glance - a funnel for the vortex, a channel for lightning, a dial for pressure, distance bands
     * for LOD. Labels are drawn in the faint text colour so the drawing reads as a diagram, not as content.
     */
    private void drawSchematic(GuiGraphics g, String name, int x, int y, int w, int h) {
        String s = name.toLowerCase(Locale.ROOT);
        int cx = x + w / 2;
        int cy = y + h / 2;
        if (s.contains("season") || s.contains("calendar") || s.contains("climate")) {
            drawCalendarSchematic(g, x, y, w, h);
            return;
        }
        if (s.contains("lightning") || s.contains("thunder") || s.contains("spc") || s.contains("risk")) {
            drawBoltSchematic(g, x, y, w, h);
            return;
        }
        if (s.contains("lod") || s.contains("compat")) {
            drawRangeSchematic(g, x, y, w, h);
            return;
        }
        if (s.contains("front") || s.contains("pressure") || s.contains("ocean") || s.contains("wave")) {
            drawGaugeSchematic(g, x, y, w, h);
            return;
        }
        if (s.contains("tornado") || s.contains("vortex") || s.contains("storm") || s.contains("physics")
                || s.contains("genesis") || s.contains("satellite")) {
            drawFunnelSchematic(g, x, y, w, h);
            return;
        }
        // Everything else: the sliders idea, three tracks with their knobs.
        int left = x + 14;
        int right = x + w - 14;
        for (int i = 0; i < 3; i++) {
            int ty = cy - 14 + i * 14;
            RoundedRectRenderer.render(g, left, ty, right - left, 3, 1.5f, 0xFF232C36);
            int knob = left + (int) ((right - left) * (0.32F + i * 0.18F));
            RoundedRectRenderer.render(g, left, ty, knob - left, 3, 1.5f, ACCENT);
            RoundedRectRenderer.renderCircle(g, knob, ty + 1.5f, 4f, 0xFFE9EEF5);
        }
    }

    /**
     * The year as four bands with today marked on it: the whole subject of a calendar category in one drawing -
     * a year divided into seasons, and a day somewhere inside it - with the sun over the bar it is counting.
     */
    private void drawCalendarSchematic(GuiGraphics g, int x, int y, int w, int h) {
        int cx = x + w / 2;
        int sunY = y + 22;
        RoundedRectRenderer.renderCircle(g, cx, sunY, 10f, ACCENT_LIGHT);
        RoundedRectRenderer.renderCircle(g, cx, sunY, 5.5f, 0xFF101720);
        int barY = y + h / 2 + 10;
        int left = x + 14;
        int right = x + w - 14;
        int band = Math.max(5, (right - left) / 4);
        for (int i = 0; i < 4; i++) {
            int bx = left + i * band;
            int bw = i == 3 ? right - bx : band - 2;
            RoundedRectRenderer.render(g, bx, barY, bw, 8, 2f, i == 0 ? ACCENT : 0xFF232C36);
        }
        int marker = left + (int) (band * 0.6f);
        RoundedRectRenderer.line(g, marker, barY - 7, marker, barY + 14, 1, 0xFFE9EEF5);
        RoundedRectRenderer.renderCircle(g, marker, barY + 17, 2.5f, 0xFFE9EEF5);
        g.drawString(font, "YEAR", left, barY + 22, TEXT_FAINT);
        RoundedRectRenderer.line(g, x + 10, y + h - 10, x + w - 10, y + h - 10, 1, PANEL_EDGE);
    }

    private void drawFunnelSchematic(GuiGraphics g, int x, int y, int w, int h) {
        int cx = x + w / 2 - 8;
        int base = y + h - 14;
        int top = y + 16;
        int rings = 7;
        for (int i = 0; i < rings; i++) {
            float f = i / (float) (rings - 1);
            float ry = base - f * (base - top);
            float rx = 8 + f * f * (w * 0.30f);
            RoundedRectRenderer.renderEllipse(g, cx, ry, rx, rx * 0.20f + 1.4f, (i % 2 == 0) ? 0xFF243040 : 0xFF1B2531);
        }
        RoundedRectRenderer.line(g, cx, base, cx, top - 6, 1, ACCENT_LIGHT);
        RoundedRectRenderer.line(g, cx + 6, base - 10, cx + 6, top + 4, 1, TEXT_FAINT);
        g.drawString(font, "R", cx + 10, top, TEXT_DIM);
        // Base bar, so the funnel reads as standing on something.
        RoundedRectRenderer.line(g, x + 10, base + 8, x + w - 10, base + 8, 1, PANEL_EDGE);
    }

    private void drawBoltSchematic(GuiGraphics g, int x, int y, int w, int h) {
        int cx = x + w / 2;
        int top = y + 12;
        int bottom = y + h - 16;
        int steps = bottom - top;
        for (int i = 0; i <= steps; i++) {
            float f = i / (float) steps;
            int offset = (int) (Math.sin(f * 9.0) * 10 * (1 - f * 0.4f));
            int px = cx + offset;
            g.fill(px, top + i, px + 2, top + i + 1, i < steps * 0.5f ? 0xFFBBD8F5 : ACCENT_LIGHT);
        }
        // One branch off partway down, the way a real channel forks.
        int by = top + (int) (steps * 0.42);
        for (int i = 0; i < 16; i++) {
            g.fill(cx - 10 - i / 2 - (int) (Math.sin(i * 0.7) * 2), by + i, cx - 8 - i / 2, by + i + 1, 0xFF3E5B78);
        }
        RoundedRectRenderer.line(g, x + 8, bottom + 6, x + w - 8, bottom + 6, 1, PANEL_EDGE);
        RoundedRectRenderer.renderEllipse(g, cx, bottom + 6, 16, 3, 0x2A6FA9E8);
    }

    private void drawGaugeSchematic(GuiGraphics g, int x, int y, int w, int h) {
        int cx = x + w / 2;
        int cy = y + h / 2 + 2;
        int r = Math.min(w, h) / 2 - 14;
        RoundedRectRenderer.renderEllipse(g, cx, cy, r, r, 0xFF1C242E);
        RoundedRectRenderer.renderEllipse(g, cx, cy, r - 2, r - 2, 0xFF0C1015);
        for (int i = 0; i <= 8; i++) {
            double a = Math.PI * (1.0 - i / 8.0);
            int tx = cx + (int) (Math.cos(a) * (r - 4));
            int ty = cy - (int) (Math.sin(a) * (r - 4));
            g.fill(tx, ty, tx + 1, ty + 1, i >= 6 ? GOLD : TEXT_FAINT);
        }
        // A needle sitting high, as a deep low pressure reading would.
        double na = Math.PI * 0.78;
        RoundedRectRenderer.line(g, cx, cy, cx + (int) (Math.cos(na) * (r - 8)), cy - (int) (Math.sin(na) * (r - 8)), 2, 0xFFE9EEF5);
        RoundedRectRenderer.renderEllipse(g, cx, cy, 3, 3, ACCENT_LIGHT);
    }

    private void drawRangeSchematic(GuiGraphics g, int x, int y, int w, int h) {
        int cx = x + w / 2;
        int cy = y + h - 18;
        RoundedRectRenderer.line(g, x + 8, cy, x + w - 8, cy, 1, PANEL_EDGE);
        // Distance bands seen from above: each ring is an outline, drawn as a filled ellipse with the panel
        // colour put back inside it, so the ring reads as a band rather than a disc.
        int[] radii = {16, 30, 46};
        String[] labels = {"4x", "LOD", "far"};
        for (int i = 0; i < radii.length; i++) {
            int r = Math.min(radii[i], h - 24);
            int band = r / 2;
            RoundedRectRenderer.renderEllipse(g, cx, cy, r, r * 0.42f, i == 1 ? 0x552F6DB5 : 0x33404A57);
            RoundedRectRenderer.renderEllipse(g, cx, cy, Math.max(1, r - band), Math.max(1f, (r - band) * 0.42f), 0xFF101720);
            g.drawString(font, labels[i], cx + r - 6, cy - (int) (r * 0.30f) - 8, TEXT_FAINT);
        }
        RoundedRectRenderer.renderEllipse(g, cx, cy, 3, 2, ACCENT_LIGHT);
    }

    /** Warm tint + left accent bar behind a jumped-to row, pulsing and fading out. */
    private void drawHighlight(GuiGraphics g, int x, int y, int w) {
        long now = Util.getMillis();
        float pulse = 0.6F + 0.4F * (float) Math.sin(now * 0.011D);
        float fade = now + 500L > highlightUntil ? (highlightUntil - now) / 500.0F : 1.0F;
        int alpha = (int) (clamp(pulse * clamp(fade, 0.0F, 1.0F), 0.0F, 1.0F) * 255.0F);
        g.fill(x, y, x + w, y + ConfigRow.HEIGHT, ((int) (alpha * 0.22F) << 24) | (GOLD & 0xFFFFFF));
        g.fill(x, y, x + 3, y + ConfigRow.HEIGHT, (alpha << 24) | (GOLD & 0xFFFFFF));
    }

    /** Re-drawn over the row content so the flash keeps a crisp edge. */
    private void drawHighlightOutline(GuiGraphics g, int x, int y, int w) {
        long now = Util.getMillis();
        float pulse = 0.6F + 0.4F * (float) Math.sin(now * 0.011D);
        float fade = now + 500L > highlightUntil ? (highlightUntil - now) / 500.0F : 1.0F;
        int alpha = (int) (clamp(pulse * clamp(fade, 0.0F, 1.0F), 0.0F, 1.0F) * 190.0F);
        int color = (alpha << 24) | (GOLD & 0xFFFFFF);
        g.fill(x, y, x + w, y + 1, color);
        g.fill(x, y + ConfigRow.HEIGHT - 1, x + w, y + ConfigRow.HEIGHT, color);
        g.fill(x + w - 1, y, x + w, y + ConfigRow.HEIGHT, color);
    }

    /** A single search result line: setting name, its category, and its current value. */
    private void renderHit(GuiGraphics g, int categoryIndex, ConfigRow row, int x, int y, int w, boolean hover) {
        int textY = y + (ConfigRow.HEIGHT - 9) / 2;
        int controlX = x + w - ConfigRow.CONTROL_W;
        String label = font.plainSubstrByWidth(row.label, Math.max(60, controlX - x - 14));
        g.drawString(font, label, x + 4, textY, hover ? 0xFFFFFFFF : TEXT);
        String value = String.valueOf(row.shown());
        g.drawString(font, value, controlX + ConfigRow.CONTROL_W - font.width(value), textY, 0xFFA8C8A8);
        String category = categories.get(categoryIndex).name;
        int catX = controlX - font.width(category) - 14;
        if (catX > x + 10 + font.width(label)) {
            g.drawString(font, category, catX, textY, TEXT_FAINT);
        }
    }

    private void renderFooter(GuiGraphics g, int mx, int my) {
        g.fill(panelX + 16, footerY, panelX + panelW - 16, footerY + 1, PANEL_EDGE);
        String msg;
        int color;
        if (errorMessage != null) {
            msg = errorMessage;
            color = 0xFFE05B5B;
        } else if (searching()) {
            msg = hits.isEmpty()
                    ? "No settings match \"" + lastQuery + "\" \u2022 Esc clears the search"
                    : hits.size() + (hits.size() == 1 ? " setting matches \"" : " settings match \"") + lastQuery
                        + "\" \u2022 Enter jumps to the first \u2022 Esc clears";
            color = hits.isEmpty() ? 0xFFE05B5B : GOLD;
        } else if (restartDirty) {
            msg = "Some changes require a restart to take effect.";
            color = GOLD;
        } else if (page == Page.SIMPLE) {
            msg = "The short version \u2022 All Settings has every one of them \u2022 Hover a dial for its detail";
            color = TEXT_DIM;
        } else {
            msg = "Values apply when you press Apply \u2022 Esc discards";
            color = TEXT_DIM;
        }
        int bx = panelX + panelW - 16 - APPLY_W;
        g.drawString(font, font.plainSubstrByWidth(msg, Math.max(60, bx - panelX - 34)), panelX + 20, footerY + 18, color);
        int by = footerY + 8;
        boolean hover = inApply(mx, my);
        RoundedRectRenderer.box(g, bx, by, APPLY_W, APPLY_H, 6, hover ? 0xFF3C7FC9 : ACCENT, ACCENT_LIGHT);
        String label = "APPLY";
        g.drawString(font, label, bx + APPLY_W / 2 - font.width(label) / 2, by + (APPLY_H - 9) / 2, 0xFFF4F8FC);
    }

    private void renderRowTooltip(GuiGraphics g, int mx, int my) {
        ConfigRow hovered = hoveredRow(mx, my);
        if (hovered == null) {
            return;
        }
        String comment = hovered.spec.getComment();
        List<Component> lines = new ArrayList<>();
        if (comment != null && !comment.isBlank()) {
            for (String line : comment.split("\n")) {
                for (String wrapped : wrap(font, line, 300)) {
                    lines.add(Component.literal(wrapped));
                    if (lines.size() > 8) {
                        break;
                    }
                }
                if (lines.size() > 8) {
                    break;
                }
            }
        }
        if (hovered.needsRestart) {
            if (!lines.isEmpty()) {
                lines.add(Component.literal(""));
            }
            ModConfigSpec.RestartType type = hovered.spec.restartType();
            lines.add(Component.literal(
                    "Requires " + (type == ModConfigSpec.RestartType.GAME ? "a game" : "a world") + " restart."
            ).withStyle(ChatFormatting.GOLD));
        }
        if (!lines.isEmpty()) {
            g.renderComponentTooltip(font, lines, mx, my);
        }
    }

    /** Word-wraps a string to the given pixel width using the current font. */
    private static List<String> wrap(Font font, String text, int maxWidth) {
        List<String> out = new ArrayList<>();
        for (String part : text.split("\n")) {
            String remaining = part;
            while (font.width(remaining) > maxWidth) {
                int cut = Math.min(remaining.length(), remaining.length() - 1);
                while (cut > 0 && font.width(remaining.substring(0, cut)) > maxWidth) {
                    int space = remaining.lastIndexOf(' ', cut - 1);
                    cut = space > 0 ? space : cut - 1;
                }
                if (cut <= 0) {
                    cut = Math.max(1, remaining.length() - 1);
                }
                out.add(remaining.substring(0, cut).trim());
                remaining = remaining.substring(cut).trim();
                if (remaining.isEmpty()) {
                    break;
                }
            }
            if (!remaining.isEmpty()) {
                out.add(remaining);
            }
        }
        return out;
    }

    private ConfigRow hoveredRow(int mx, int my) {
        if (searching()) {
            return null; // Results are navigation; the row under the cursor is not a control.
        }
        if (page == Page.SIMPLE) {
            if (mx < simpleX() || mx > simpleX() + simpleW() || my < contentY || my > contentY + simpleViewportH()) {
                return null;
            }
            List<SimplePage.Dial> dials = dials();
            int card = SimplePage.indexAt(my, dials.size(), contentY, (int) simpleScroll, simpleViewportH());
            return card < 0 ? null : dialRow(dials.get(card));
        }
        if (mx < bodyX || mx > bodyX + rowsW || my < rowsTop || my > bodyY + bodyH) {
            return null;
        }
        int i = (int) ((my - rowsTop + bodyScroll) / ConfigRow.HEIGHT);
        List<ConfigRow> rows = visibleRows();
        if (i < 0 || i >= rows.size()) {
            return null;
        }
        return rows.get(i);
    }

    // ---- search ----

    private String query() {
        return searchBox == null ? lastQuery : searchBox.getValue().trim().toLowerCase(Locale.ROOT);
    }

    /**
     * Whether the search results are what the body is showing.
     *
     * <p>Gated on the page as well as on the query: results are a view of the detailed list, so the simple page
     * is never in search mode however the field was left. That one gate is what keeps the footer, the body and
     * the row hit test from each needing to know about the pages separately.
     */
    private boolean searching() {
        return page == Page.ALL && !query().isEmpty();
    }

    /** The rows currently rendered: every match across all categories while searching, else this category. */
    private List<ConfigRow> visibleRows() {
        return searching() ? hitRows : rows();
    }

    /**
     * Collects every setting whose name or current value contains the query. The results keep the sidebar order,
     * so "jumping" is just remembering which category each hit came from.
     */
    private void rebuildHits() {
        hits.clear();
        hitRows.clear();
        String q = query();
        if (q.isEmpty()) {
            return;
        }
        for (int i = 0; i < categories.size(); i++) {
            for (ConfigRow row : categories.get(i).rows) {
                if (matches(row, q)) {
                    hits.add(new Hit(i, row));
                    hitRows.add(row);
                }
            }
        }
    }

    private static boolean matches(ConfigRow row, String q) {
        if (row.label.toLowerCase(Locale.ROOT).contains(q)) {
            return true;
        }
        Object value = row.shown();
        return value != null && String.valueOf(value).toLowerCase(Locale.ROOT).contains(q);
    }

    /** Selects a hit's category, scrolls it near the top of the body and flashes it. */
    private void jumpTo(Hit hit) {
        reveal(hit.category(), hit.row());
    }

    /**
     * Opens the detailed list at one setting and flashes it.
     *
     * <p>The single path behind both a search result and a dial's detail chip: they are the same promise - "this
     * setting is that way" - so they land the same way, on the same page, with the same flash.
     */
    private void reveal(int categoryIndex, ConfigRow row) {
        List<ConfigRow> categoryRows = categories.get(categoryIndex).rows;
        int index = categoryRows.indexOf(row);
        if (index < 0) {
            return;
        }
        blurText();
        page = Page.ALL;
        selected = categoryIndex;
        expanded = categoryIndex;
        bodyScroll = Math.max(0, index * (double) ConfigRow.HEIGHT - ConfigRow.HEIGHT);
        simpleScroll = 0;
        activeRow = null;
        errorMessage = null;
        highlightRow = row;
        highlightUntil = Util.getMillis() + HIGHLIGHT_MILLIS;
        clearSearch();
    }

    private void clearSearch() {
        if (searchBox != null) {
            searchBox.setValue("");
            searchBox.setFocused(false);
        }
        lastQuery = "";
        hits.clear();
        hitRows.clear();
    }

    // ---- interaction ----

    @Override
    public boolean mouseClicked(double mx, double my, int btn) {
        if (mx >= searchPillX && mx <= searchPillX + searchPillW
                && my >= searchPillY && my <= searchPillY + searchPillH) {
            blurText();
            searchBox.setFocused(true);
            searchBox.mouseClicked(mx, my, btn);
            return true;
        }
        if (searchBox != null && searchBox.isFocused()) {
            searchBox.setFocused(false);
        }
        if (btn == 0 && inApply(mx, my)) {
            applyAll();
            return true;
        }
        if (btn == 0 && inTabs(mx, my)) {
            for (Tab tab : tabs()) {
                if (mx >= tab.x() && mx <= tab.x() + tab.w() && my >= tab.y() && my <= tab.y() + tab.h()) {
                    switchPage(tab.page());
                    return true;
                }
            }
            return true; // The band itself is not a target.
        }
        if (page == Page.SIMPLE) {
            if (!inBody(mx, my)) {
                blurText();
                return super.mouseClicked(mx, my, btn);
            }
            int x = simpleX();
            int w = simpleW();
            int trackX = x + w - 6;
            if (mx >= trackX - 6 && maxSimpleScroll > 0) {
                draggingThumb = true;
                simpleScroll = clamp((my - contentY) / (double) simpleViewportH() * maxSimpleScroll, 0, maxSimpleScroll);
                return true;
            }
            List<SimplePage.Dial> dials = dials();
            int card = SimplePage.indexAt(my, dials.size(), contentY, (int) simpleScroll, simpleViewportH());
            if (card < 0) {
                blurText();
                return true;
            }
            int cardY = SimplePage.cardTop(card, contentY, (int) simpleScroll);
            ConfigRow row = dialRow(dials.get(card));
            // The chips are drawn over the card's lower line and are checked first, because that is the order
            // they are stacked in: the control row above never overlaps them, but a click between the two must
            // not fall through to the card behind.
            for (Chip chip : chipsFor(x, cardY, w - 12, row)) {
                if (mx >= chip.x() && mx <= chip.x() + chip.w()
                        && my >= chip.y() && my <= chip.y() + chip.h()) {
                    reveal(chip.category(), chip.row());
                    return true;
                }
            }
            activeRow = row;
            blurText();
            row.mouseClicked(mx, my, btn);
            return true;
        }
        if (inSidebar(mx, my)) {
            for (SideLine line : sideLines()) {
                if (my < line.y() || my > line.y() + line.h()) {
                    continue;
                }
                if (line.sub() >= 0) {
                    // A sub-entry scrolls the body to the settings that stretch holds.
                    if (line.category() != selected) {
                        select(line.category());
                    }
                    List<Sub> subs = categories.get(line.category()).subs;
                    if (line.sub() < subs.size()) {
                        bodyScroll = Math.max(0, subs.get(line.sub()).firstRow() * (double) ConfigRow.HEIGHT - 4);
                        highlightRow = null;
                    }
                    return true;
                }
                // The simple category is not a list of settings to scroll - it is the other page, and the pill
                // is the second way to it for anyone who looked in the sidebar first.
                if (SIMPLE_NAME.equals(categories.get(line.category()).name)) {
                    switchPage(Page.SIMPLE);
                    return true;
                }
                // Selecting a category expands it; clicking the one already open collapses it again, which is
                // what the chevron promises. The pill and the chevron do the same thing so neither can mislead.
                if (line.category() != selected) {
                    select(line.category());
                    expanded = line.category();
                } else if (expanded == line.category()) {
                    expanded = -1;
                } else {
                    expanded = line.category();
                }
                return true;
            }
            return true;
        }
        if (inBody(mx, my)) {
            int trackX = bodyX + bodyW - 6;
            if (mx >= trackX - 6 && maxBodyScroll > 0) {
                draggingThumb = true;
                bodyScroll = (my - bodyY - 26) / (double) (bodyH - 26) * maxBodyScroll;
                return true;
            }
            if (mx > bodyX + rowsW) {
                blurText();
                return true; // The illustration column is not interactive.
            }
            int i = (int) ((my - rowsTop + bodyScroll) / ConfigRow.HEIGHT);
            if (searching()) {
                // Results are navigation, not controls: clicking one jumps to the real setting.
                if (i >= 0 && i < hits.size()) {
                    jumpTo(hits.get(i));
                } else {
                    blurText();
                }
                return true;
            }
            List<ConfigRow> rows = rows();
            if (i >= 0 && i < rows.size()) {
                ConfigRow row = rows.get(i);
                activeRow = row;
                blurText();
                row.mouseClicked(mx, my, btn);
                return true;
            }
            blurText();
            return true;
        }
        blurText();
        return super.mouseClicked(mx, my, btn);
    }

    @Override
    public boolean mouseDragged(double mx, double my, int btn, double dx, double dy) {
        if (activeRow != null && activeRow.mouseDragged(mx, my, dx, dy)) {
            return true;
        }
        if (draggingThumb && page == Page.SIMPLE && maxSimpleScroll > 0) {
            double viewportH = simpleViewportH();
            double thumb = simpleThumbH(dials().size());
            if (viewportH > thumb) {
                simpleScroll = clamp((my - contentY - thumb / 2) / (viewportH - thumb) * maxSimpleScroll,
                        0, maxSimpleScroll);
                return true;
            }
        }
        if (draggingThumb && page == Page.ALL && maxBodyScroll > 0 && bodyH - 26 > thumbH) {
            bodyScroll = (my - bodyY - 26 - thumbH / 2) / (bodyH - 26 - thumbH) * maxBodyScroll;
            return true;
        }
        return super.mouseDragged(mx, my, btn, dx, dy);
    }

    @Override
    public boolean mouseReleased(double mx, double my, int btn) {
        draggingThumb = false;
        if (activeRow != null) {
            activeRow.mouseReleased(mx, my);
            activeRow = null;
            return true;
        }
        return super.mouseReleased(mx, my, btn);
    }

    @Override
    public boolean mouseScrolled(double mx, double my, double horizontal, double vertical) {
        double delta = vertical;
        if (page == Page.SIMPLE) {
            if (inBody(mx, my)) {
                simpleScroll = clamp(simpleScroll - delta * 32, 0, maxSimpleScroll);
                return true;
            }
            return super.mouseScrolled(mx, my, horizontal, vertical);
        }
        if (inBody(mx, my)) {
            if (!searching() && mx <= bodyX + rowsW) {
                int i = (int) ((my - rowsTop + bodyScroll) / ConfigRow.HEIGHT);
                List<ConfigRow> rows = rows();
                if (i >= 0 && i < rows.size() && rows.get(i).mouseScrolled(mx, my, delta)) {
                    return true;
                }
            }
            bodyScroll -= delta * 28;
            return true;
        }
        if (inSidebar(mx, my)) {
            sidebarScroll -= delta * SIDE_ITEM_H;
            return true;
        }
        return super.mouseScrolled(mx, my, horizontal, vertical);
    }

    @Override
    public boolean keyPressed(int key, int scancode, int mods) {
        if (searchBox != null && searchBox.isFocused()) {
            if (key == GLFW.GLFW_KEY_ESCAPE) {
                if (!searchBox.getValue().isEmpty()) {
                    // First Esc clears the filter, a second one leaves the field.
                    searchBox.setValue("");
                } else {
                    searchBox.setFocused(false);
                }
                return true;
            }
            if (key == GLFW.GLFW_KEY_ENTER || key == GLFW.GLFW_KEY_KP_ENTER || key == GLFW.GLFW_KEY_DOWN) {
                // Refresh here too: a keystroke and the Enter that follows it can arrive in the same
                // frame, before renderBody has had a chance to rebuild the match list.
                rebuildHits();
                if (!hits.isEmpty()) {
                    jumpTo(hits.get(0));
                }
                return true;
            }
            searchBox.keyPressed(key, scancode, mods);
            return true;
        }
        EditBox box = focusedBox();
        if (box != null) {
            if (key == GLFW.GLFW_KEY_ESCAPE) {
                box.setFocused(false);
                blurText();
                return true;
            }
            box.keyPressed(key, scancode, mods);
            return true;
        }
        if (key == GLFW.GLFW_KEY_ESCAPE) {
            onClose();
            return true;
        }
        if (key == GLFW.GLFW_KEY_ENTER || key == GLFW.GLFW_KEY_KP_ENTER) {
            applyAll();
            return true;
        }
        return super.keyPressed(key, scancode, mods);
    }

    @Override
    public boolean charTyped(char code, int mods) {
        if (searchBox != null && searchBox.isFocused()) {
            return searchBox.charTyped(code, mods);
        }
        EditBox box = focusedBox();
        if (box != null) {
            return box.charTyped(code, mods);
        }
        return super.charTyped(code, mods);
    }

    // ---- state ----

    /** Every text box anywhere, rather than only the ones on the page in front: a box left focused behind a
     * page switch would keep swallowing the keyboard. */
    private EditBox focusedBox() {
        for (Category category : categories) {
            for (ConfigRow r : category.rows) {
                if (r instanceof TextRow tr && tr.box.isFocused()) {
                    return tr.box;
                }
            }
        }
        return null;
    }

    private void blurText() {
        for (Category category : categories) {
            for (ConfigRow r : category.rows) {
                if (r instanceof TextRow tr && tr.box.isFocused()) {
                    tr.box.setFocused(false);
                    tr.validate();
                }
            }
        }
    }

    private void select(int i) {
        blurText();
        selected = i;
        bodyScroll = 0;
        activeRow = null;
        errorMessage = null;
        // Picking a category leaves search mode, so the sidebar always shows that category's rows.
        clearSearch();
    }

    private void applyAll() {
        errorMessage = null;
        restartDirty = false;
        for (Category cat : categories) {
            for (ConfigRow row : cat.rows) {
                if (!row.apply()) {
                    errorMessage = "Invalid value in '" + row.label + "' - fix it before pressing Apply.";
                    return;
                }
                if (row.isDirty() && row.needsRestart) {
                    restartDirty = true;
                }
            }
        }
        Config.SPEC.save();
        onClose();
    }

    @Override
    public void onClose() {
        if (minecraft != null) {
            minecraft.setScreen(parent);
        }
    }

    @Override
    public boolean isPauseScreen() {
        return false;
    }

    private static double clamp(double v, double min, double max) {
        return Math.max(min, Math.min(max, v));
    }
