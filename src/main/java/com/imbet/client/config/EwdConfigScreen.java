    @Override
    protected void init() {
        // Never taller than the window: a fixed minimum could push the header (and the Apply button) off
        // screen on a small logical resolution, leaving a panel that cannot be used.
        panelW = Math.min(MAX_PANEL_W, Math.max(420, width - 16));
        panelH = Math.min(MAX_PANEL_H, Math.max(220, height - 16));
        panelX = (width - panelW) / 2;
        panelY = (height - panelH) / 2;
        int margin = 16;
        tabY = panelY + HEADER_H + 6;
        contentY = tabY + TAB_H + 8;
        footerY = panelY + panelH - FOOTER_H;
        sidebarX = panelX + margin;
        sidebarY = contentY;
        sidebarW = Math.min(SIDEBAR_W, Math.max(150, panelW / 3)) - 4;
        sidebarH = Math.max(60, footerY - contentY - 8);
        bodyX = panelX + sidebarW + margin + 8;
        bodyY = sidebarY;
        bodyW = panelW - (bodyX - panelX) - margin;
        bodyH = sidebarH;

        // The illustration panel takes a column off the right of the body when there is room for both it and a
        // usable row width; below that the rows keep the whole width and the panel is skipped.
        int candidate = bodyW - ILLUS_W - 14;
        if (candidate >= 330) {
            illusW = ILLUS_W;
            illusX = bodyX + bodyW - ILLUS_W;
            rowsW = candidate;
        } else {
            illusW = 0;
            illusX = 0;
            rowsW = bodyW - 20;
        }
        rowsTop = bodyY + 26;

        searchPillW = SEARCH_W + 32;
        searchPillH = SEARCH_H + 10;
        searchPillX = panelX + panelW - margin - searchPillW;
        searchPillY = panelY + 13;
        searchBox = new EditBox(font, searchPillX + 10, searchPillY + 5, SEARCH_W, SEARCH_H, Component.literal("Search"));
        searchBox.setHint(Component.literal("Search settings"));
        searchBox.setMaxLength(48);
        searchBox.setValue(lastQuery);
        searchBox.setBordered(false);
        searchBox.setTextColor(TEXT);
    }

    private List<ConfigRow> rows() {
        return categories.get(selected).rows;
    }

    private boolean inBody(double mx, double my) {
        return mx >= bodyX && mx <= bodyX + bodyW && my >= bodyY && my <= bodyY + bodyH;
    }

    private boolean inSidebar(double mx, double my) {
        // The sidebar is only drawn on the detailed page: on the simple page that column is the cards, so a
        // click there must not be read as a click on a category.
        return page == Page.ALL
                && mx >= sidebarX && mx <= sidebarX + sidebarW && my >= sidebarY && my <= sidebarY + sidebarH;
    }

    private boolean inApply(double mx, double my) {
        int bx = panelX + panelW - 16 - APPLY_W;
        int by = footerY + 8;
        return mx >= bx && mx <= bx + APPLY_W && my >= by && my <= by + APPLY_H;
    }

    /**
     * The sidebar's lines for the current expansion and scroll. Rendered and hit-tested from the same list, so a
     * click can never land on a different line than the one under the cursor.
     */
    private List<SideLine> sideLines() {
        List<SideLine> lines = new ArrayList<>();
        int y = sidebarY - (int) sidebarScroll;
        for (int i = 0; i < categories.size(); i++) {
            lines.add(new SideLine(i, -1, y, SIDE_ITEM_H));
            y += SIDE_ITEM_H;
            if (i == expanded) {
                for (int s = 0; s < categories.get(i).subs.size(); s++) {
                    lines.add(new SideLine(i, s, y, SUB_ITEM_H));
                    y += SUB_ITEM_H;
                }
                y += 2;
            }
        }
        return lines;
    }

    private double maxSidebarScroll() {
        int used = 0;
        for (int i = 0; i < categories.size(); i++) {
            used += SIDE_ITEM_H;
            if (i == expanded) {
                used += categories.get(i).subs.size() * SUB_ITEM_H + 2;
            }
        }
        return Math.max(0, used - sidebarH);
    }

    // ---- render ----

    @Override
    public void render(GuiGraphics g, int mx, int my, float pt) {
        // The search lives in the detailed list, because that is where the results are: typing in it from the
        // simple page would otherwise fill a box with a query whose matches are on another page.
        if (page == Page.SIMPLE && !query().isEmpty()) {
            page = Page.ALL;
        }
        g.fill(0, 0, width, height, 0xFF05070A);
        RoundedRectRenderer.box(g, panelX, panelY, panelW, panelH, 10, PANEL_BG, PANEL_EDGE);
        renderHeader(g, mx, my, pt);
        renderTabs(g, mx, my);
        if (page == Page.ALL) {
            renderSidebar(g, mx, my);
            renderBody(g, mx, my, pt);
        } else {
            renderSimplePage(g, mx, my, pt);
        }
        renderFooter(g, mx, my);
        renderRowTooltip(g, mx, my);
    }

    /** One page tab: which page it opens, its label and its rect. */
    private record Tab(Page page, String label, int x, int y, int w, int h) {
    }

    /**
     * The two page tabs, laid out from the panel's left edge. Computed on demand and used by both the renderer
     * and the click handler, so a click cannot land on a tab other than the one under the cursor.
     */
    private List<Tab> tabs() {
        List<Tab> tabs = new ArrayList<>();
        int x = panelX + 16;
        for (Page candidate : new Page[] {Page.SIMPLE, Page.ALL}) {
            String label = candidate == Page.SIMPLE ? TAB_SIMPLE : TAB_ALL;
            int w = Math.max(84, font.width(label) + 26);
            tabs.add(new Tab(candidate, label, x, tabY, w, TAB_H));
            x += w + TAB_GAP;
        }
        return tabs;
    }

    private boolean inTabs(double mx, double my) {
        return my >= tabY && my <= tabY + TAB_H;
    }

    private void renderTabs(GuiGraphics g, int mx, int my) {
        List<Tab> tabs = tabs();
        for (Tab tab : tabs) {
            boolean active = tab.page() == page;
            boolean hover = mx >= tab.x() && mx <= tab.x() + tab.w() && my >= tab.y() && my <= tab.y() + tab.h();
            RoundedRectRenderer.box(g, tab.x(), tab.y(), tab.w(), tab.h(), 5,
                    active ? 0xFF17202B : (hover ? PILL_HOVER : PILL_BG),
                    active ? ACCENT : (hover ? ACCENT_LIGHT : PANEL_EDGE));
            String label = spaceOut(tab.label());
            int textX = tab.x() + (tab.w() - font.width(label)) / 2;
            if (tab.page() == Page.SIMPLE) {
                textX += 7;
                g.drawString(font, SIMPLE_GLYPH, tab.x() + 11, tab.y() + (tab.h() - 9) / 2, active ? ACCENT_LIGHT : TEXT_FAINT);
            }
            g.drawString(font, label, textX, tab.y() + (tab.h() - 9) / 2, active ? 0xFFEAF2FB : TEXT_DIM);
        }
        // What the page is for, in the space between the last tab and the search field.
        Tab last = tabs.get(tabs.size() - 1);
        int after = last.x() + last.w() + 14;
        int room = searchPillX - after - 12;
        if (room > 60) {
            String summary = page == Page.SIMPLE ? SimplePage.SUMMARY : "Every category and every setting, in full";
            g.drawString(font, font.plainSubstrByWidth(summary, room), after, tabY + (TAB_H - 9) / 2 + 1, TEXT_FAINT);
        }
    }

    /** Moves between the two pages, leaving no transient interaction from the page being left behind. */
    private void switchPage(Page target) {
        if (page == target) {
            return;
        }
        page = target;
        blurText();
        activeRow = null;
        draggingThumb = false;
        bodyScroll = 0;
        simpleScroll = 0;
        errorMessage = null;
        if (target == Page.SIMPLE) {
            // Nothing on the simple page is searchable, so a query left set would make the footer report
            // results that are not on screen - and the next keystroke would flip the page back.
            clearSearch();
        }
    }

    private int simpleX() {
        return panelX + 16;
    }

    private int simpleW() {
        return panelW - 32;
    }

    private int simpleViewportH() {
        return Math.max(20, footerY - contentY - 8);
    }

    /** The scroll thumb's height on the simple page: the share of the list the viewport can show. */
    private double simpleThumbH(int cards) {
        int viewportH = simpleViewportH();
        int content = Math.max(1, SimplePage.contentHeight(cards));
        return Math.max(24, viewportH * (viewportH / (double) content));
    }

    /** The simple section's category, or null in a build whose config has no simple settings. */
    private Category simpleCategory() {
        for (Category category : categories) {
            if (SIMPLE_NAME.equals(category.name)) {
                return category;
            }
        }
        return null;
    }

    /** The simple section's row for a dial - the very same row the detailed page edits, not a copy of it. */
    private ConfigRow dialRow(SimplePage.Dial dial) {
        Category simple = simpleCategory();
        if (simple == null) {
            return null;
        }
        for (ConfigRow row : simple.rows) {
            if (ConfigRow.last(row.value.getPath()).equals(dial.key())) {
                return row;
            }
        }
        return null;
    }

    /** The dials this config actually has, in the table's order. A dial with no setting behind it is not drawn. */
    private List<SimplePage.Dial> dials() {
        List<SimplePage.Dial> dials = new ArrayList<>();
        for (SimplePage.Dial dial : SimplePage.DIALS) {
            if (dialRow(dial) != null) {
                dials.add(dial);
            }
        }
        return dials;
    }

    /** A detail chip's destination: the category it lives in, the row, and the name to label it with. */
    private record Resolved(int category, ConfigRow row, String label) {
    }

    /**
     * A dial's declared detail, resolved against the categories that were actually built from the config.
     *
     * <p>Null when the category or the setting is not there, which is what keeps a chip from being drawn for a
     * setting that has been renamed or removed: a chip that leads nowhere is worse than no chip.
     */
    private Resolved resolveTarget(SimplePage.Target target) {
        String name = categoryName(target.categoryKey());
        for (int i = 0; i < categories.size(); i++) {
            Category category = categories.get(i);
            if (!category.name.equals(name)) {
                continue;
            }
            for (ConfigRow row : category.rows) {
                if (ConfigRow.last(row.value.getPath()).equals(target.rowKey())) {
                    return new Resolved(i, row, name);
                }
            }
        }
        return null;
    }

    /** One detail chip: its rect on screen and what clicking it reveals. */
    private record Chip(int category, ConfigRow row, String label, int x, int y, int w, int h) {
    }

    /**
     * The chips of one card, laid out from the card's right edge leftwards.
     *
     * <p>Called by the renderer to draw them and by the click handler to hit-test them, from the same
     * arithmetic, so the chip under the cursor is the chip that gets clicked.
     */
    private List<Chip> chipsFor(int cardX, int cardY, int cardW, ConfigRow row) {
        List<Chip> chips = new ArrayList<>();
        if (row == null) {
            return chips;
        }
        SimplePage.Dial dial = SimplePage.dial(ConfigRow.last(row.value.getPath()));
        if (dial == null) {
            return chips;
        }
        int x = cardX + cardW - 14;
        int y = SimplePage.cardChipY(cardY);
        for (int i = dial.targets().size() - 1; i >= 0; i--) {
            Resolved resolved = resolveTarget(dial.targets().get(i));
            if (resolved == null) {
                continue;
            }
            String label = resolved.label().toUpperCase(Locale.ROOT) + " \u2192";
            int w = font.width(label) + 16;
            if (x - w < cardX + 10) {
                break;
            }
            x -= w;
            chips.add(new Chip(resolved.category(), resolved.row(), label, x, y, w, SimplePage.CHIP_H));
            x -= 6;
        }
        return chips;
    }

    /**
     * The simple page: one card per dial, each card holding the real setting's own row, the sentence that says
     * what the dial does at the value it currently has, and the chips that open its detail.
     */
    private void renderSimplePage(GuiGraphics g, int mx, int my, float pt) {
        List<SimplePage.Dial> dials = dials();
        int x = simpleX();
        int w = simpleW();
        int viewportH = simpleViewportH();
        maxSimpleScroll = SimplePage.maxScroll(dials.size(), viewportH);
        simpleScroll = clamp(simpleScroll, 0, maxSimpleScroll);
        if (maxSimpleScroll > 0) {
            double thumbH = simpleThumbH(dials.size());
            double thumbY = contentY + (viewportH - thumbH) * (simpleScroll / maxSimpleScroll);
            int trackX = x + w - 6;
            g.fill(trackX, contentY, trackX + 3, contentY + viewportH, 0xFF161B21);
            RoundedRectRenderer.render(g, trackX, (float) thumbY, 3, (float) thumbH, 1.5f, 0xFF5C6672);
        }
        g.enableScissor(x, contentY, x + w, contentY + viewportH);
        for (int i = 0; i < dials.size(); i++) {
            int cardY = SimplePage.cardTop(i, contentY, (int) simpleScroll);
            if (cardY + SimplePage.CARD_H < contentY || cardY > contentY + viewportH) {
                continue;
            }
            SimplePage.Dial dial = dials.get(i);
            ConfigRow row = dialRow(dial);
            boolean hover = mx >= x && mx <= x + w && my >= cardY && my <= cardY + SimplePage.CARD_H;
            RoundedRectRenderer.box(g, x, cardY, w - 12, SimplePage.CARD_H, 7,
                    hover ? 0xFF141A21 : 0xFF10151B, hover ? PANEL_EDGE : 0xFF1B2229);
            // The setting, drawn by its own row: the same label and the same control as the detailed page.
            row.render(g, font, x + 8, cardY + SimplePage.CARD_PAD_TOP, w - 28, mx, my, pt);
            List<Chip> chips = chipsFor(x, cardY, w - 12, row);
            int chipsLeft = chips.isEmpty() ? x + w : chips.get(0).x();
            int room = Math.max(40, chipsLeft - x - 24);
            int lineY = SimplePage.cardLineY(cardY);
            String question = font.plainSubstrByWidth("\u2022 " + dial.question() + " \u2014 ", room);
            g.drawString(font, question, x + 12, lineY, TEXT_FAINT);
            String sentence = font.plainSubstrByWidth(SimplePage.effect(dial.key(), row.shown()),
                    Math.max(20, room - font.width(question)));
            g.drawString(font, sentence, x + 12 + font.width(question), lineY, hover ? TEXT : TEXT_DIM);
            for (Chip chip : chips) {
                boolean over = mx >= chip.x() && mx <= chip.x() + chip.w()
                        && my >= chip.y() && my <= chip.y() + chip.h();
                RoundedRectRenderer.box(g, chip.x(), chip.y(), chip.w(), chip.h(), 4,
                        over ? 0xFF232C36 : PILL_BG, over ? ACCENT_LIGHT : PANEL_EDGE);
                g.drawString(font, chip.label(), chip.x() + 8, chip.y() + (chip.h() - 9) / 2 + 1,
                        over ? 0xFFEAF2FB : TEXT_DIM);
            }
        }
        g.disableScissor();
    }

    private static String spaceOut(String s) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            if (i > 0) {
                sb.append(' ');
            }
            sb.append(s.charAt(i));
        }
        return sb.toString();
    }

